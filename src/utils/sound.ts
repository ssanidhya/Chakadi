export function triggerHapticVibration(pattern: number | number[] = 30): void {
  try {
    if (typeof window !== 'undefined' && 'vibrate' in navigator) {
      navigator.vibrate(pattern);
    }
  } catch (e) {
    // Ignore unsupported devices
  }
}
